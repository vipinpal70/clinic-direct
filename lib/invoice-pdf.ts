import PDFDocument from "pdfkit";
import { currencyExact, dateFmt } from "@/lib/utils";

export interface InvoiceForPdf {
  number: string;
  commission: number;
  vat: number;
  total: number;
  status: string;
  periodStart: Date | null;
  periodEnd: Date | null;
  createdAt: Date;
}

export interface ClinicForPdf {
  name: string;
  code: string;
}

/**
 * Renders a self-billed invoice as a PDF and resolves the raw bytes as a Buffer.
 * Shared by the email attachment (lib/mailer.ts) and the download endpoint
 * (app/api/invoices/[id]/pdf) so both produce an identical document.
 */
export function generateInvoicePdf(
  clinic: ClinicForPdf,
  invoice: InvoiceForPdf,
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 50 });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const left = doc.page.margins.left;
    const right = doc.page.width - doc.page.margins.right;
    const ink = "#111827";
    const muted = "#6b7280";

    // ── Header ──────────────────────────────────────────────────────────
    doc.fillColor(ink).fontSize(20).font("Helvetica-Bold").text("Self-billed invoice", left, 50);
    doc.fillColor(muted).fontSize(11).font("Helvetica").text("Clinic Direct", left, 76);

    doc.fillColor(muted).fontSize(10).font("Helvetica").text("Invoice number", left, 50, {
      width: right - left,
      align: "right",
    });
    doc.fillColor(ink).fontSize(14).font("Helvetica-Bold").text(invoice.number, left, 64, {
      width: right - left,
      align: "right",
    });

    doc.moveTo(left, 100).lineTo(right, 100).lineWidth(2).strokeColor(ink).stroke();

    // ── Meta rows ───────────────────────────────────────────────────────
    const period =
      invoice.periodStart && invoice.periodEnd
        ? `${dateFmt(invoice.periodStart)} - ${dateFmt(invoice.periodEnd)}`
        : "-";
    const meta: [string, string][] = [
      ["Billed to", `${clinic.name} (${clinic.code})`],
      ["Issue date", dateFmt(invoice.createdAt)],
      ["Period", period],
      ["Status", invoice.status.charAt(0).toUpperCase() + invoice.status.slice(1)],
    ];
    let y = 120;
    for (const [label, value] of meta) {
      doc.fontSize(11).font("Helvetica").fillColor(muted).text(label, left, y);
      doc.font("Helvetica-Bold").fillColor(ink).text(value, left, y, {
        width: right - left,
        align: "right",
      });
      y += 20;
    }

    // ── Amount rows ─────────────────────────────────────────────────────
    y += 16;
    const row = (label: string, value: string, opts?: { bold?: boolean; rule?: "thin" | "thick" }) => {
      if (opts?.rule) {
        doc
          .moveTo(left, y - 6)
          .lineTo(right, y - 6)
          .lineWidth(opts.rule === "thick" ? 2 : 1)
          .strokeColor(opts.rule === "thick" ? ink : "#e5e7eb")
          .stroke();
      }
      const font = opts?.bold ? "Helvetica-Bold" : "Helvetica";
      doc.font(font).fontSize(opts?.bold ? 14 : 12).fillColor(ink);
      doc.text(label, left, y);
      doc.text(value, left, y, { width: right - left, align: "right" });
      y += opts?.bold ? 26 : 22;
    };
    row("Commission", currencyExact(invoice.commission), { rule: "thin" });
    row("VAT (20%)", currencyExact(invoice.vat), { rule: "thin" });
    row("Total", currencyExact(invoice.total), { bold: true, rule: "thick" });

    // ── Footer note ─────────────────────────────────────────────────────
    doc
      .fontSize(9)
      .font("Helvetica")
      .fillColor(muted)
      .text(
        "This self-billed invoice was generated by Clinic Direct on your behalf under your partnership agreement.",
        left,
        y + 24,
        { width: right - left },
      );

    doc.end();
  });
}
